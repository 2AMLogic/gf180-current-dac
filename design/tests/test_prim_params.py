#!/usr/bin/env python3
"""Unit tests for PRIM_PARAMS in design/gen_analog.py (issue #163).

The five layout primitives are the unit cells of the matched array, so a
well-formed but wrong `w_um` (or a wrong `rows`/`cols`/`dummy`) is a
geometry error CI must see — previously it surfaced only on a local
`layout/gen_prims.sh --check` run that needs PDK_ROOT.

The oracle is the committed `layout/prims/*.report.json`, generated by
`klt gen mos_array` from these very params: `ports[0].width_um` records
the transistor width and `device_count` the number of explicit devices.
Comparing against the reports is not a second copy of the numbers — it
catches the stale-prims drift where `gen_analog.py` is resized but
`layout/gen_prims.sh` is not rerun, because the array generator consumes
the committed `layout/prims/*.gds`.

Not covered: `l_um`, `gate_contact`, `dummy`, `flavor` and the structural
flags are asserted against the `_prim` contract only. The reports record
no channel length (`provenance.input` is null), and the only geometric
trace of L, `bbox_um`, mixes it with klt-version-specific routing offsets
(x-span = L + 3.04 for the nfets, + 3.44 for the pfet), so no report
field pins `l_um` independently of the params under test.

Stdlib only; no klayout, klt or PDK needed. Verify with
`python3 -m unittest design.tests.test_prim_params` from the repo root
(or let `python3 scripts/check_ci.py` run it as part of TESTS).
"""

import importlib.util
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

_spec = importlib.util.spec_from_file_location(
    "gen_analog_under_test", ROOT / "design" / "gen_analog.py")
gen_analog = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen_analog)

PRIM_NAMES = ["prim_cs", "prim_cas", "prim_sw", "prim_drvn", "prim_drvp"]


def report(name):
    return json.loads(
        (ROOT / "layout" / "prims" / f"{name}.report.json").read_text())


class TestAgainstCommittedReports(unittest.TestCase):
    """w_um and rows*cols must match the committed klt reports."""

    def test_prims_are_exactly_the_five_named(self):
        # A renamed or added primitive must not silently escape the report
        # comparison below.
        self.assertEqual(sorted(gen_analog.PRIM_PARAMS), sorted(PRIM_NAMES))

    def test_w_um_matches_report_port_width(self):
        for name in PRIM_NAMES:
            with self.subTest(prim=name):
                port0 = report(name)["ports"][0]
                self.assertEqual(
                    port0["name"], "U0_S",
                    "report port order changed; pick the source port by name")
                self.assertAlmostEqual(
                    gen_analog.PRIM_PARAMS[name]["w_um"],
                    port0["width_um"])

    def test_rows_times_cols_matches_report_device_count(self):
        for name in PRIM_NAMES:
            with self.subTest(prim=name):
                p = gen_analog.PRIM_PARAMS[name]
                self.assertEqual(p["rows"] * p["cols"],
                                 report(name)["device_count"])


class TestPrimContract(unittest.TestCase):
    """The `_prim` docstring contract: one explicit device per primitive.

    The array's instance-for-instance matching (layout and LVS, per-cell
    Monte Carlo mismatch) depends on these flags; see `_prim` in
    design/gen_analog.py.
    """

    def test_single_explicit_device(self):
        for name, p in gen_analog.PRIM_PARAMS.items():
            with self.subTest(prim=name):
                self.assertEqual(p["rows"], 1)
                self.assertEqual(p["cols"], 1)
                self.assertEqual(p["dummy"], 0)
                self.assertIs(p["gate_contact"], True)

    def test_flavor_pfet_only_on_drvp(self):
        for name, p in gen_analog.PRIM_PARAMS.items():
            with self.subTest(prim=name):
                if name == "prim_drvp":
                    self.assertEqual(p.get("flavor"), "pfet")
                else:
                    self.assertNotIn("flavor", p)


if __name__ == "__main__":
    unittest.main()
